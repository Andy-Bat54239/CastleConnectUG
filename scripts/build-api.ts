/**
 * Bundles the two server routes (server/*.ts) into self-contained files in api/, which is where Vercel looks for functions.
 * Each bundle has everything it needs inside it, so Vercel never has to resolve imports at run time (a common cause of
 * "module not found" errors in functions). The bundles are committed, and `npm run build` rebuilds them, and a test fails
 * if the committed ones are out of date.
 *
 *   npm run build:api
 */
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..')

export const ROUTES = ['track', 'stats'] as const

export async function bundleApi(outDir: string): Promise<void> {
  for (const name of ROUTES) {
    await build({
      entryPoints: [join(root, 'server', `${name}.ts`)],
      outfile: join(outDir, `${name}.js`),
      bundle: true,
      format: 'esm',
      platform: 'node',
      target: 'node20',
      legalComments: 'none',
      banner: { js: `// Generated by scripts/build-api.ts from server/${name}.ts. Do not edit; run "npm run build:api".` },
      logLevel: 'warning',
    })
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await bundleApi(join(root, 'api'))
  console.log(`Wrote api/${ROUTES.join('.js, api/')}.js`)
}
